func TestEmit_OrdersBySourceLine(t *testing.T) {
	got, err := Emit(Config{Package: "h"}, []Annotation{
		{Func: "Third", Keyword: "query", Line: 30},
		{Func: "First", Keyword: "provide", Line: 10},
		{Func: "Second", Keyword: "rest", Args: []string{"GET", "/2"}, Line: 20},
	})
	if err != nil {
		t.Fatal(err)
	}
	s := string(got)
	iFirst, iSecond, iThird := strings.Index(s, "First"), strings.Index(s, "Second"), strings.Index(s, "Third")
	if !(iFirst < iSecond && iSecond < iThird) {
		t.Fatalf("statements not ordered by source line:\n%s", s)
	}
}

