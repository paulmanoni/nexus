func TestEmit_FullCatalog(t *testing.T) {
	anns := []Annotation{
		{Func: "NewUsersService", Keyword: "provide", Line: 10},
		{Func: "NewGetUser", Keyword: "rest", Args: []string{"GET", "/users/:id"}, Line: 20},
		{Func: "NewCreateUser", Keyword: "mutation", Line: 30},
		{Func: "NewCreateUser", Keyword: "auth", Args: []string{`Requires("ADMIN")`}, Line: 31},
		{Func: "NewSearch", Keyword: "query", Line: 40},
		{Func: "NewChatSend", Keyword: "ws", Args: []string{"/events", "chat.send"}, Line: 50},
		{Func: "NewChatSend", Keyword: "auth", Args: []string{"Required"}, Line: 51},
		{Func: "NewReaper", Keyword: "worker", Args: []string{"reaper"}, Line: 60},
	}
	got, err := Emit(Config{Package: "handlers"}, anns)
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	want := `// Code generated by "nexus generate handlers"; DO NOT EDIT.

package handlers

import (
	"github.com/paulmanoni/nexus"
	"github.com/paulmanoni/nexus/decorate"
	"github.com/paulmanoni/nexus/extension/auth"
)

func init() {
	decorate.Register(nexus.Module("handlers",
		nexus.Provide(NewUsersService),
		nexus.AsRest("GET", "/users/:id", NewGetUser),
		nexus.AsMutation(NewCreateUser, auth.Requires("ADMIN")),
		nexus.AsQuery(NewSearch),
		nexus.AsWS("/events", "chat.send", NewChatSend, auth.Required()),
		nexus.AsWorker("reaper", NewReaper),
	))
}
`
	if string(got) != want {
		t.Fatalf("generated source mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

