func TestEmit_ModuleFromPackageWithMainFallback(t *testing.T) {
	// Normal package → module is the package name.
	got, _ := Emit(Config{Package: "users"}, []Annotation{{Func: "F", Keyword: "query", Line: 1}})
	if !strings.Contains(string(got), `decorate.Register(nexus.Module("users",`) {
		t.Fatalf("module should be package name:\n%s", got)
	}
	// main package → friendly default so it isn't a "main" node on the dashboard.
	got, _ = Emit(Config{Package: "main"}, []Annotation{{Func: "F", Keyword: "query", Line: 1}})
	if !strings.Contains(string(got), `decorate.Register(nexus.Module("`+DefaultModule+`",`) {
		t.Fatalf("main package should fall back to %q module:\n%s", DefaultModule, got)
	}
}

func TestEmit_UseModifierWithImport(t *testing.T) {
	got, err := Emit(Config{Package: "h"}, []Annotation{
		{Func: "NewX", Keyword: "rest", Args: []string{"POST", "/x"}, Line: 1},
		{Func: "NewX", Keyword: "use", Args: []string{"ratelimit.Per(time.Minute,", "60)"}, Line: 2,
			Imports: []string{`"github.com/paulmanoni/nexus/extension/ratelimit"`, `"time"`}},
	})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	s := string(got)
	if !strings.Contains(s, `nexus.AsRest("POST", "/x", NewX, ratelimit.Per(time.Minute, 60))`) {
		t.Fatalf("use expression not emitted as opt:\n%s", s)
	}
	if !strings.Contains(s, `"github.com/paulmanoni/nexus/extension/ratelimit"`) || !strings.Contains(s, `"time"`) {
		t.Fatalf("use imports missing:\n%s", s)
	}
}

func TestEmit_CustomQualifiedDecorator(t *testing.T) {
	got, err := Emit(Config{Package: "h"}, []Annotation{
		{Func: "NewDash", Keyword: "inertia.Page", Args: []string{`"GET"`, `"/dash"`, `"Dashboard"`}, Line: 1,
			Imports: []string{`"github.com/paulmanoni/nexus/extension/inertia"`}},
		{Func: "NewBare", Keyword: "widgets.Mount", Line: 2,
			Imports: []string{`"example.com/widgets"`}},
	})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	s := string(got)
	if !strings.Contains(s, `inertia.Page("GET", "/dash", "Dashboard", NewDash)`) {
		t.Fatalf("qualified decorator with args not emitted:\n%s", s)
	}
	if !strings.Contains(s, `widgets.Mount(NewBare)`) {
		t.Fatalf("qualified decorator without args not emitted:\n%s", s)
	}
	if !strings.Contains(s, `"github.com/paulmanoni/nexus/extension/inertia"`) || !strings.Contains(s, `"example.com/widgets"`) {
		t.Fatalf("custom decorator imports missing:\n%s", s)
	}
	// Custom decorators are wrapped in nexus.Module like everything else.
	if !strings.Contains(s, `decorate.Register(nexus.Module(`) {
		t.Fatalf("custom decorators not wrapped in nexus.Module:\n%s", s)
	}
}

func TestEmit_CustomDecoratorAppendsModifiers(t *testing.T) {
	// A modifier on a custom //@pkg.Func decorator is appended as a trailing
	// option: inertia.Page(args…, fn, auth.Required()). The registrar must accept
	// the option type (inertia.Page takes ...nexus.RestOption).
	got, err := Emit(Config{Package: "h"}, []Annotation{
		{Func: "F", Keyword: "inertia.Page", Args: []string{`"GET"`, `"/x"`, `"X"`}, Line: 1, Imports: []string{`"x/inertia"`}},
		{Func: "F", Keyword: "auth", Args: []string{"Required"}, Line: 2},
	})
	if err != nil {
		t.Fatalf("custom decorator + modifier should be allowed, got: %v", err)
	}
	s := string(got)
	if !strings.Contains(s, `inertia.Page("GET", "/x", "X", F, auth.Required())`) {
		t.Fatalf("modifier not appended to custom decorator call:\n%s", s)
	}
	if !strings.Contains(s, `"github.com/paulmanoni/nexus/extension/auth"`) {
		t.Fatalf("auth import missing for custom decorator modifier:\n%s", s)
	}
}

