func method(recv, name, kw string, line int, args ...string) Annotation {
	return Annotation{Func: "(*" + recv + ")." + name, Recv: recv, Method: name, Keyword: kw, Args: args, Line: line}
}

func TestEmit_Controller(t *testing.T) {
	inertiaImport := []string{`"github.com/paulmanoni/nexus/v2/extension/inertia"`}
	anns := []Annotation{
		{Func: "NewUsersController", Keyword: "provide", Line: 5},
		{Func: "UsersController", Keyword: "controller", Args: []string{"/users"}, Line: 10, TypeLevel: true},
		{Func: "UsersController", Keyword: "auth", Args: []string{"Required"}, Line: 11, TypeLevel: true},
		method("UsersController", "Index", "page", 20, "GET", `""`),
		method("UsersController", "Show", "page", 30, "GET", "/:id/view", "Admin/UserDetail"),
		method("UsersController", "Show", "page", 30, "GET", "/:id/view/", "Admin/UserDetail"),
		method("UsersController", "Show", "auth", 31, "Requires", "view_user"),
		{Func: "(*UsersController).Form", Recv: "UsersController", Method: "Form", Keyword: "inertia.Page",
			Args: []string{"GET,POST", "/:id/form", "Users/Form"}, Line: 40, Imports: inertiaImport},
		method("UsersController", "Export", "rest", 50, "GET", "/export"),
		method("UsersController", "UserRows", "query", 60),
		method("UsersController", "SaveUser", "mutation", 70),
		method("UsersController", "SaveUser", "auth", 71, "Requires", "add_user"),
		// A method on a type without //@controller registers as a method expression.
		method("Helpers", "Ping", "rest", 80, "GET", "/ping"),
		{Func: "NewAbout", Keyword: "page", Args: []string{"GET", "/about", "About"}, Line: 90},
	}
	got, err := Emit(Config{Package: "users"}, anns)
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	want := `// Code generated by "nexus generate handlers"; DO NOT EDIT.

package users

import (
	"github.com/paulmanoni/nexus/v2"
	"github.com/paulmanoni/nexus/v2/decorate"
	"github.com/paulmanoni/nexus/v2/extension/auth"
	"github.com/paulmanoni/nexus/v2/extension/inertia"
)

func init() {
	decorate.Register(nexus.Module("users",
		nexus.Provide(NewUsersController),
		nexus.Controller[*UsersController]("/users", auth.Required()).
			Rest("GET", "", (*UsersController).Index, inertia.Component("Users/Index")).
			Rest("GET", "/:id/view", (*UsersController).Show, inertia.Component("Admin/UserDetail"), auth.Requires("view_user")).
			Rest("GET", "/:id/view/", (*UsersController).Show, inertia.Component("Admin/UserDetail"), auth.Requires("view_user")).
			Rest("GET", "/:id/form", (*UsersController).Form, inertia.Component("Users/Form")).
			Rest("POST", "/:id/form", (*UsersController).Form, inertia.Component("Users/Form")).
			Rest("GET", "/export", (*UsersController).Export).
			Query((*UsersController).UserRows).
			Mutation((*UsersController).SaveUser, auth.Requires("add_user")),
		nexus.ControllerActions(func(c *nexus.ControllerRouter[*Helpers]) {
			c.Rest("GET", "/ping", (*Helpers).Ping)
		}),
		inertia.Page("GET", "/about", "About", NewAbout),
	))
}
`
	if string(got) != want {
		t.Fatalf("generated source mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestEmit_ControllerErrors(t *testing.T) {
	ctl := Annotation{Func: "C", Keyword: "controller", Args: []string{"/c"}, Line: 1, TypeLevel: true, File: "c.go"}
	cases := []struct {
		name string
		anns []Annotation
		want string
	}{
		{"auth without controller", []Annotation{
			{Func: "C", Keyword: "auth", Args: []string{"Required"}, Line: 1, TypeLevel: true, File: "c.go"},
			method("C", "Index", "page", 5, "GET", "/")},
			"needs //@controller"},
		{"primary on a type", []Annotation{{Func: "C", Keyword: "rest", Args: []string{"GET", "/"}, Line: 1, TypeLevel: true, File: "c.go"}},
			"cannot annotate a type"},
		{"controller on a method", []Annotation{method("C", "Index", "controller", 3, "/c")}, "annotates a type"},
		{"two primaries on a function", []Annotation{
			{Func: "NewX", Keyword: "rest", Args: []string{"GET", "/x"}, Line: 1},
			{Func: "NewX", Keyword: "rest", Args: []string{"GET", "/x/"}, Line: 2}}, "registers exactly once"},
		{"query and page on an action", []Annotation{ctl,
			method("C", "Rows", "page", 3, "GET", "/rows"), method("C", "Rows", "query", 4)}, "registers exactly once"},
		{"ws on an action", []Annotation{ctl, method("C", "Chat", "ws", 3, "/ws", "chat")}, "not available on a controller action"},
		{"relative path", []Annotation{ctl, method("C", "Show", "page", 3, "GET", ":id")}, `must start with "/"`},
		{"bad prefix", []Annotation{{Func: "C", Keyword: "controller", Args: []string{"c"}, Line: 1, TypeLevel: true}}, `must start with "/"`},
		{"page without component on a function", []Annotation{{Func: "NewX", Keyword: "page", Args: []string{"GET", "/x"}, Line: 1}},
			"may be left out only on a //@controller"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Emit(Config{Package: "p"}, tc.anns)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("want error containing %q, got %v", tc.want, err)
			}
		})
	}
}

func TestEmit_ControllerTrailingSlash(t *testing.T) {
	got, err := Emit(Config{Package: "p"}, []Annotation{
		{Func: "C", Keyword: "controller", Args: []string{"/c", "trailing-slash"}, Line: 1, TypeLevel: true},
		method("C", "Index", "rest", 3, "GET", "/"),
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "nexus.Controller[*C](\"/c\").\n\t\t\tTrailingSlash().\n\t\t\tRest(\"GET\", \"\", (*C).Index)") {
		t.Fatalf("TrailingSlash not emitted:\n%s", got)
	}
	_, err = Emit(Config{Package: "p"}, []Annotation{
		{Func: "C", Keyword: "controller", Args: []string{"/c", "slashes"}, Line: 1, TypeLevel: true, File: "c.go"},
	})
	if err == nil || !strings.Contains(err.Error(), "the one option is trailing-slash") {
		t.Fatalf("unknown controller option: %v", err)
	}
}

func TestEmit_Job(t *testing.T) {
	got, err := Emit(Config{Package: "reports"}, []Annotation{
		{Func: "NewReportService", Keyword: "provide", Line: 1},
		method("ReportService", "Generate", "job", 5, "low", "timeout=2h", "retry=3", "unique=90s"),
		{Func: "SendDigest", Keyword: "job", Line: 9},
		{Func: "C", Keyword: "controller", Args: []string{"/c"}, Line: 12, TypeLevel: true},
		method("C", "Index", "page", 14, "GET", "/"),
		method("C", "Rebuild", "job", 16, "name=rebuild-index"),
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		`jobs.Define((*ReportService).Generate, jobs.Queue("low"), jobs.Timeout(2*time.Hour), jobs.Retry(3), jobs.Unique(90*time.Second)),`,
		`jobs.DefineFunc(SendDigest),`,
		`jobs.Define((*C).Rebuild, jobs.Name("rebuild-index")),`,
		`"github.com/paulmanoni/nexus/v2/extension/jobs"`,
		`"time"`,
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("missing %s in:\n%s", want, got)
		}
	}
	for _, tc := range []struct {
		args []string
		want string
	}{
		{[]string{"retry=-1"}, "not a count"},
		{[]string{"timeout=soon"}, "not a duration"},
		{[]string{"priority=high"}, "unknown option"},
		{[]string{"retry=1", "low"}, "queue name comes first"},
	} {
		_, err := Emit(Config{Package: "p"}, []Annotation{{Func: "J", Keyword: "job", Args: tc.args, Line: 1, File: "j.go"}})
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("//@job %v: want error containing %q, got %v", tc.args, tc.want, err)
		}
	}
	_, err = Emit(Config{Package: "p"}, []Annotation{
		{Func: "J", Keyword: "job", Line: 1, File: "j.go"},
		{Func: "J", Keyword: "auth", Args: []string{"Required"}, Line: 2, File: "j.go"},
	})
	if err == nil || !strings.Contains(err.Error(), "does not accept modifier") {
		t.Errorf("//@auth on a job: %v", err)
	}
}

// Annotated methods of a type without //@controller are collected into one
// nexus.ControllerActions call, paths as written, for a Go-declared controller.
func TestEmit_ImplicitActions(t *testing.T) {
	inertiaImport := []string{`"github.com/paulmanoni/nexus/v2/extension/inertia"`}
	anns := []Annotation{
		method("DashboardController", "Index", "page", 10, "GET", "/", "Admin/Dashboard"),
		method("DashboardController", "Index", "auth", 11, "Required"),
		method("DashboardController", "Forbidden", "page", 20, "GET", "/forbidden"),
		{Func: "(*DashboardController).Form", Recv: "DashboardController", Method: "Form", Keyword: "inertia.Page",
			Args: []string{"GET,POST", "/form", "Admin/Form"}, Line: 30, Imports: inertiaImport},
		method("DashboardController", "Stats", "query", 40),
	}
	got, err := Emit(Config{Package: "admin"}, anns)
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	for _, want := range []string{
		"nexus.ControllerActions(func(c *nexus.ControllerRouter[*DashboardController]) {\n",
		`c.Rest("GET", "/", (*DashboardController).Index, inertia.Component("Admin/Dashboard"), auth.Required())`,
		`c.Rest("GET", "/forbidden", (*DashboardController).Forbidden, inertia.Component("Dashboard/Forbidden"))`,
		`c.Rest("GET", "/form", (*DashboardController).Form, inertia.Component("Admin/Form"))`,
		`c.Rest("POST", "/form", (*DashboardController).Form, inertia.Component("Admin/Form"))`,
		`c.Query((*DashboardController).Stats)`,
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("generated file lacks %s:\n%s", want, got)
		}
	}
	if _, err := Emit(Config{Package: "admin"}, []Annotation{method("DashboardController", "Index", "page", 10, "GET", "rel")}); err == nil {
		t.Error("a relative path without //@controller must be rejected")
	}
}
