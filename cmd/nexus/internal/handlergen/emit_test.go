func TestEmit_ModuleFromPackageWithMainFallback(t *testing.T) {
	// Normal package → module is the package name.
	got, _ := Emit(Config{Package: "users"}, []Annotation{{Func: "F", Keyword: "query", Line: 1}})
	if !strings.Contains(string(got), `decorate.Register(nexus.Module("users",`) {
		t.Fatalf("module should be package name:\n%s", got)
	}
	// main package → friendly default so it isn't a "main" node on the dashboard.
	got, _ = Emit(Config{Package: "main"}, []Annotation{{Func: "F", Keyword: "query", Line: 1}})
	if !strings.Contains(string(got), `decorate.Register(nexus.Module("`+DefaultModule+`",`) {
		t.Fatalf("main package should fall back to %q module:\n%s", DefaultModule, got)
	}
}

