// TestEmit_InertiaPageNormalization: //@inertia.Page takes bare tokens (or
// quoted ones), case-normalises the verbs, and rejects malformed values at
// the annotation — instead of emitting invalid Go into the generated file.
func TestEmit_InertiaPageNormalization(t *testing.T) {
	inertiaImp := []string{`"github.com/paulmanoni/nexus/v2/extension/inertia"`}

	ok := func(args []string, want string) {
		t.Helper()
		got, err := Emit(Config{Package: "h"}, []Annotation{
			{Func: "NewUsers", Keyword: "inertia.Page", Args: args, Imports: inertiaImp, Line: 1},
		})
		if err != nil {
			t.Fatalf("Emit(%v): %v", args, err)
		}
		if !strings.Contains(string(got), want) {
			t.Errorf("Emit(%v) missing %q:\n%s", args, want, got)
		}
	}
	// Bare tokens, quoted tokens, and mixed case all land on the same call.
	ok([]string{"GET", "/users", "Users/Index"}, `inertia.Page("GET", "/users", "Users/Index", NewUsers)`)
	ok([]string{`"GET"`, `"/users"`, `"Users/Index"`}, `inertia.Page("GET", "/users", "Users/Index", NewUsers)`)
	ok([]string{"get,post", "/login", "Login"}, `inertia.Page("GET,POST", "/login", "Login", NewUsers)`)

	bad := func(args []string, want string) {
		t.Helper()
		_, err := Emit(Config{Package: "h"}, []Annotation{
			{Func: "NewUsers", Keyword: "inertia.Page", Args: args, Imports: inertiaImp, File: "h/p.go", Line: 4},
		})
		if err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("Emit(%v): error %v, want containing %q", args, err, want)
		}
		if err != nil && !strings.Contains(err.Error(), "h/p.go:4:") {
			t.Errorf("Emit(%v): error %v lacks file:line", args, err)
		}
	}
	bad([]string{"GET", "/users"}, "needs <METHOD> <PATH> <Component>")
	bad([]string{"FETCH", "/users", "Users/Index"}, "not an HTTP method")
	bad([]string{"GET", "users", "Users/Index"}, `must start with "/"`)

	// A .Page decorator from some OTHER package keeps the verbatim contract.
	got, err := Emit(Config{Package: "h"}, []Annotation{
		{Func: "F", Keyword: "cms.Page", Args: []string{`"a"`, `slug`}, Imports: []string{`"example.com/cms"`}, Line: 1},
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), `cms.Page("a", slug, F)`) {
		t.Errorf("foreign .Page decorator must pass through verbatim:\n%s", got)
	}
}

// TestEmit_AuthGrammar: the //@auth modifier reads naturally — bare tokens,
// case-insensitive capability, unquoted permissions, a Public marking — while
// the legacy call form keeps working; typos fail at the annotation with a
// suggestion instead of an undefined identifier in the generated file.
func TestEmit_AuthGrammar(t *testing.T) {
	rest := Annotation{Func: "NewX", Keyword: "rest", Args: []string{"GET", "/x"}, Line: 1}

	ok := func(authArgs []string, want string, wantAuthImport bool) {
		t.Helper()
		got, err := Emit(Config{Package: "h"}, []Annotation{rest,
			{Func: "NewX", Keyword: "auth", Args: authArgs, Line: 2},
		})
		if err != nil {
			t.Fatalf("Emit(auth %v): %v", authArgs, err)
		}
		if !strings.Contains(string(got), want) {
			t.Errorf("Emit(auth %v) missing %q:\n%s", authArgs, want, got)
		}
		hasImport := strings.Contains(string(got), `"github.com/paulmanoni/nexus/v2/extension/auth"`)
		if hasImport != wantAuthImport {
			t.Errorf("Emit(auth %v): auth import present = %v, want %v", authArgs, hasImport, wantAuthImport)
		}
	}
	ok([]string{"Required"}, "auth.Required()", true)
	ok([]string{"required"}, "auth.Required()", true) // capability is case-insensitive
	ok([]string{"Requires", "ADMIN"}, `auth.Requires("ADMIN")`, true)
	ok([]string{"Requires", "ADMIN", "HR"}, `auth.Requires("ADMIN", "HR")`, true)
	ok([]string{"Requires", `"ROLE X"`}, `auth.Requires("ROLE X")`, true) // quoted keeps spaces
	ok([]string{"Public"}, "nexus.Public()", false)
	ok([]string{"Required()"}, "auth.Required()", true)                    // legacy call form
	ok([]string{`Requires("A",`, `"B")`}, `auth.Requires("A", "B")`, true) // legacy multi-role

	bad := func(authArgs []string, want string) {
		t.Helper()
		_, err := Emit(Config{Package: "h"}, []Annotation{rest,
			{Func: "NewX", Keyword: "auth", Args: authArgs, File: "h/a.go", Line: 2},
		})
		if err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("Emit(auth %v): error %v, want containing %q", authArgs, err, want)
		}
		if err != nil && !strings.Contains(err.Error(), "h/a.go:2:") {
			t.Errorf("Emit(auth %v): error %v lacks file:line", authArgs, err)
		}
	}
	bad(nil, "needs a capability")
	bad([]string{"Requires"}, "needs at least one permission")
	bad([]string{"Required", "ADMIN"}, "//@auth Requires ADMIN") // steers to the right spelling
	bad([]string{"Requeired"}, "did you mean Required?")
	bad([]string{"Admin"}, "unknown //@auth capability")
}

// TestEmit_SessionGrammar: the //@session modifier — bare or call-form
// Required, case-insensitive, with positioned errors and a did-you-mean.
func TestEmit_SessionGrammar(t *testing.T) {
	rest := Annotation{Func: "NewX", Keyword: "rest", Args: []string{"GET", "/x"}, Line: 1}
	for _, args := range [][]string{{"Required"}, {"required"}, {"Required()"}} {
		got, err := Emit(Config{Package: "h"}, []Annotation{rest,
			{Func: "NewX", Keyword: "session", Args: args, Line: 2},
		})
		if err != nil {
			t.Fatalf("Emit(session %v): %v", args, err)
		}
		if !strings.Contains(string(got), "session.Required()") ||
			!strings.Contains(string(got), `"github.com/paulmanoni/nexus/v2/extension/session"`) {
			t.Errorf("Emit(session %v) missing gate or import:\n%s", args, got)
		}
	}

	bad := func(args []string, want string) {
		t.Helper()
		_, err := Emit(Config{Package: "h"}, []Annotation{rest,
			{Func: "NewX", Keyword: "session", Args: args, File: "h/s.go", Line: 2},
		})
		if err == nil || !strings.Contains(err.Error(), want) || !strings.Contains(err.Error(), "h/s.go:2:") {
			t.Errorf("Emit(session %v): error %v, want positioned error containing %q", args, err, want)
		}
	}
	bad(nil, "needs a capability")
	bad([]string{"Required", "extra"}, "takes no arguments")
	bad([]string{"Requierd"}, "did you mean Required?")
	bad([]string{"Fresh"}, "unknown //@session capability")
}

func TestEmit_Errors(t *testing.T) {
	cases := []struct {
		name string
		anns []Annotation
		want string
	}{
		{"two primaries", []Annotation{
			{Func: "F", Keyword: "rest", Args: []string{"GET", "/a"}, Line: 1},
			{Func: "F", Keyword: "query", Line: 2},
		}, "two primary"},
		{"modifier without primary", []Annotation{
			{Func: "F", Keyword: "auth", Args: []string{"Required"}, Line: 1},
		}, "no primary"},
		{"auth on provide", []Annotation{
			{Func: "F", Keyword: "provide", Line: 1},
			{Func: "F", Keyword: "auth", Args: []string{"Required"}, Line: 2},
		}, "does not accept modifier"},
		{"rest missing args", []Annotation{
			{Func: "F", Keyword: "rest", Args: []string{"GET"}, Line: 1},
		}, "needs <METHOD> <PATH>"},
		{"unknown keyword", []Annotation{{Func: "F", Keyword: "bogus", Line: 1}}, "unknown annotation"},
		{"worker missing name", []Annotation{{Func: "F", Keyword: "worker", Line: 1}}, "needs exactly a <name>"},
		{"rest bad method", []Annotation{
			{Func: "F", Keyword: "rest", Args: []string{"FETCH", "/a"}, Line: 1},
		}, "not an HTTP method"},
		{"rest bad path", []Annotation{
			{Func: "F", Keyword: "rest", Args: []string{"GET", "users"}, Line: 1},
		}, `must start with "/"`},
		{"query with args", []Annotation{
			{Func: "F", Keyword: "query", Args: []string{"userList"}, Line: 1},
		}, "takes no arguments"},
		{"provide with args", []Annotation{
			{Func: "F", Keyword: "provide", Args: []string{"x"}, Line: 1},
		}, "takes no arguments"},
		{"auth bad expression", []Annotation{
			{Func: "F", Keyword: "rest", Args: []string{"GET", "/a"}, Line: 1},
			{Func: "F", Keyword: "auth", Args: []string{`Requires("A"`}, Line: 2},
		}, "not valid Go"},
		{"positioned error", []Annotation{
			{Func: "F", Keyword: "rest", Args: []string{"GET"}, File: "h/x.go", Line: 7},
		}, "h/x.go:7:"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			_, err := Emit(Config{Package: "h"}, c.anns)
			if err == nil {
				t.Fatalf("expected error containing %q, got nil", c.want)
			}
			if !strings.Contains(err.Error(), c.want) {
				t.Fatalf("error %q does not contain %q", err, c.want)
			}
		})
	}
}

