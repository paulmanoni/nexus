// Icon renders the named icon; class sizes and colours it (default size-3.5).
// An unknown name renders nothing.
func Icon(name string, class ...string) templ.Component {
	return templ.ComponentFunc(func(_ context.Context, w io.Writer) error {
		body, ok := paths[name]
		if !ok {
			return nil
		}
		c := "size-3.5 shrink-0"
		if len(class) > 0 && class[0] != "" {
			c = class[0]
		}
		_, err := io.WriteString(w, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" class="`+html.EscapeString(c)+`">`+body+`</svg>`)
		return err
	})
}
