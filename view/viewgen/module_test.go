package viewgen

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, src := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// A page in one package renders a shard in another that Uses a state struct
// from a third: the shard inherits the page's gates — including one whose
// package only the page's file imports — and main links every package.
func TestModule(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":  "module example.com/app\n\ngo 1.26\n",
		"main.go": "package main\n\nfunc main() {}\n",
		"state/state.go": `package state

import "github.com/paulmanoni/nexus/view"

type Search struct {
	Query *view.Signal[string]
	Label string
}
`,
		"pages/home.templ": `package pages

import (
	"example.com/app/guards"
	"example.com/app/pets"
)

//@page GET /
//@auth Required
//@use guards.Admin()
templ Home() {
	@pets.Results()
}
`,
		"pets/results.templ": `package pets

import (
	"github.com/paulmanoni/nexus/view"
	"example.com/app/state"
)

templ Results() {
	{{ s := view.Use[*state.Search](ctx) }}
	{{ rows := find(s.Query.Get()) }}
	for _, r := range rows {
		<li>{ r }</li>
	}
	<input value={ s.Query.Get() }/>
}
`,
	})
	if _, err := Module(root); err != nil {
		t.Fatal(err)
	}
	read := func(name string) string {
		b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	pets := read("pets/view_gen.go")
	for _, want := range []string{
		`view.Shard(Results, auth.Required(), guards.Admin())`,
		`"example.com/app/guards"`,
		`"github.com/paulmanoni/nexus/extension/auth"`,
		`view.Expose[*state.Search]()`,
		`"example.com/app/state"`,
		`c[\"s.Query\"].get()`, // the compiled JavaScript, inside a Go string
	} {
		if !strings.Contains(pets, want) {
			t.Errorf("pets/view_gen.go lacks %s:\n%s", want, pets)
		}
	}
	if !strings.Contains(read("pets/results_templ.go"), `view.ShardEnd(Results, []any{}, []any{s.Query})`) {
		t.Error("Results reads the state struct's Query on the server, so it is a shard watching it")
	}
	if !strings.Contains(read("pages/view_gen.go"), `view.Page("GET", "/", Home, auth.Required(), guards.Admin())`) {
		t.Error("the page is registered with its gates")
	}
	imports := read("view_imports_gen.go")
	if !strings.Contains(imports, `_ "example.com/app/pages"`) || !strings.Contains(imports, `_ "example.com/app/pets"`) {
		t.Errorf("main must link the registering packages:\n%s", imports)
	}
}

// Overlay mode generates the same files without writing into the tree, and
// hides a stale generated file; a main package outside the app's directory
// tree does not link the app's packages.
func TestOverlay(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":             "module example.com/app\n\ngo 1.26\n",
		"app/main.go":        "package main\n\nfunc main() {}\n",
		"tools/lint/main.go": "package main\n\nfunc main() {}\n",
		"app/pages/home.templ": `package pages

//@page GET /
templ Home() {
	<p>hi</p>
}
`,
		"app/ui/view_gen.go": "// Code generated by nexus; DO NOT EDIT.\n\npackage ui\n", // stale: ui has no templates any more
	})
	out := t.TempDir()
	overlay, err := Overlay(root, out)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(overlay)
	var ov struct{ Replace map[string]string }
	if err := json.Unmarshal(b, &ov); err != nil {
		t.Fatal(err)
	}
	for _, rel := range []string{"app/pages/home_templ.go", "app/pages/view_gen.go", "app/view_imports_gen.go"} {
		path := filepath.Join(root, filepath.FromSlash(rel))
		tmp, ok := ov.Replace[path]
		if !ok || tmp == "" {
			t.Errorf("overlay does not generate %s", rel)
			continue
		}
		if _, err := os.Stat(path); err == nil {
			t.Errorf("%s was written into the tree", rel)
		}
		if !strings.HasPrefix(tmp, out) {
			t.Errorf("%s is generated outside the overlay dir: %s", rel, tmp)
		}
	}
	if tmp, ok := ov.Replace[filepath.Join(root, "app", "ui", "view_gen.go")]; !ok || tmp != "" {
		t.Error("a stale generated file must be hidden from the build")
	}
	if _, ok := ov.Replace[filepath.Join(root, "tools", "lint", "view_imports_gen.go")]; ok {
		t.Error("a main package outside the app's tree must not link its packages")
	}
}

// Generating twice leaves the tree as the first run wrote it: a file this
// run generates is never also swept as stale.
func TestModuleTwice(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"go.mod":  "module example.com/app\n\ngo 1.26\n",
		"main.go": "package main\n\nfunc main() {}\n",
		"pages/home.templ": `package pages

//@page GET /
templ Home() {
	<p>hi</p>
}
`,
	})
	first, err := Module(root)
	if err != nil {
		t.Fatal(err)
	}
	second, err := Module(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(first) == 0 || len(second) != 0 {
		t.Fatalf("first run changed %v, second %v — the second must change nothing", first, second)
	}
	if _, err := os.Stat(filepath.Join(root, "view_imports_gen.go")); err != nil {
		t.Fatal("the main package's imports file must survive a second run")
	}
}
